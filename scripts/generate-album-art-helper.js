#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

// Read devotionals file
const devotionalsPath = path.join(__dirname, '../constants/devotionals.ts');
const devotionalsContent = fs.readFileSync(devotionalsPath, 'utf8');

// Extract all devotional titles using regex
const titleMatches = devotionalsContent.matchAll(/title:\s*['"](.*?)['"]/g);
const devotionTitles = Array.from(titleMatches).map(match => match[1]);

console.log(`✅ Found ${devotionTitles.length} devotions`);

// Convert title to kebab-case filename
function toKebabCase(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .trim();
}

// Check which MP3 files actually exist
const audioDir = path.join(__dirname, '../assets/audio');
const existingMp3Files = fs.readdirSync(audioDir)
  .filter(f => f.endsWith('.mp3'))
  .map(f => f.replace('.mp3', ''));

console.log(`📁 Found ${existingMp3Files.length} MP3 files in assets/audio/`);

// Check which JPG files actually exist
const existingJpgFiles = fs.readdirSync(audioDir)
  .filter(f => f.endsWith('.jpg'))
  .map(f => f.replace('.jpg', ''));

console.log(`🖼️  Found ${existingJpgFiles.length} JPG files in assets/audio/`);

// Generate switch cases only for files that have BOTH .mp3 AND .jpg
const casesWithAlbumArt = devotionTitles
  .map((title, index) => {
    const fileName = toKebabCase(title);
    const dayNumber = index + 1;
    const hasMp3 = existingMp3Files.includes(fileName);
    const hasJpg = existingJpgFiles.includes(fileName);
    
    if (hasMp3 && hasJpg) {
      return `      // Day ${dayNumber}: ${title}\n      case '${fileName}':\n        return require('@/assets/audio/${fileName}.jpg');`;
    }
    return null;
  })
  .filter(Boolean)
  .join('\n      \n');

console.log(`✅ Generated ${casesWithAlbumArt.split('case').length - 1} album art mappings`);

// Generate the albumArtHelper.ts file
const albumArtHelperContent = `// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// Generated by: scripts/generate-album-art-helper.js
// 
// This file maps devotion titles to their album art images.
// Album art is automatically extracted from MP3 files using scripts/extract-album-art.sh

/**
 * Converts devotion title to kebab-case filename
 */
export function getAudioFileForDevotion(devotionTitle: string): string {
  const fileName = devotionTitle
    .toLowerCase()
    .replace(/[^a-z0-9\\s-]/g, '')
    .replace(/\\s+/g, '-')
    .replace(/-+/g, '-')
    .trim();
  
  return fileName;
}

/**
 * Gets album art for a devotion by title.
 * Returns the image source or null if no album art exists.
 */
export function getAlbumArtForDevotion(devotionTitle: string): any | null {
  const fileName = getAudioFileForDevotion(devotionTitle);
  
  try {
    switch (fileName) {
${casesWithAlbumArt}
      
      default:
        console.log(\`ℹ️  No album art found for: \${fileName}.jpg\`);
        return null;
    }
  } catch (error) {
    console.log(\`⚠️  Could not load album art: \${fileName}.jpg\`, error);
    return null;
  }
}
`;

// Write the file
const outputPath = path.join(__dirname, '../utils/albumArtHelper.ts');
fs.writeFileSync(outputPath, albumArtHelperContent);

console.log(`✅ Generated albumArtHelper.ts with ${casesWithAlbumArt.split('case').length - 1} album art mappings\n`);
console.log('🎨 Album art is now auto-registered!');
