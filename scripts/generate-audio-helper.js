/**
 * Auto-generates audioHelper.ts with all 365 devotion audio mappings
 * 
 * Run this script whenever you update devotionals.ts:
 * node scripts/generate-audio-helper.js
 */

const fs = require('fs');
const path = require('path');

// Read devotionals file
const devotionalsPath = path.join(__dirname, '../constants/devotionals.ts');
const devotionalsContent = fs.readFileSync(devotionalsPath, 'utf8');

// Extract devotionals array
const devotionalsMatch = devotionalsContent.match(/export const devotionals: Devotional\[\] = \[([\s\S]*?)\];/);
if (!devotionalsMatch) {
  console.error('❌ Could not find devotionals array');
  process.exit(1);
}

// Extract all titles using regex
const titleMatches = [...devotionalsContent.matchAll(/title: "([^"]+)"/g)];
const devotionTitles = titleMatches.map(match => match[1]);

console.log(`✅ Found ${devotionTitles.length} devotions`);

// Convert title to kebab-case
function toKebabCase(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '') // Remove special characters
    .replace(/\s+/g, '-') // Replace spaces with hyphens
    .replace(/-+/g, '-') // Replace multiple hyphens with single hyphen
    .trim();
}

// Generate all case statements
const caseStatements = devotionTitles.map((title, index) => {
  const fileName = toKebabCase(title);
  const dayNumber = index + 1;
  return `      // Day ${dayNumber}: ${title}
      case '${fileName}':
        return require('@/assets/audio/${fileName}.mp3');`;
}).join('\n      \n');

// Generate the complete audioHelper.ts file
const audioHelperContent = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by: scripts/generate-audio-helper.js
 * 
 * This file maps devotion titles to their corresponding audio files.
 * Audio files should be placed in /assets/audio/ with kebab-case names.
 * 
 * To update this file:
 * 1. Update constants/devotionals.ts if needed
 * 2. Run: node scripts/generate-audio-helper.js
 * 3. Add your MP3 files to /assets/audio/
 * 4. Rebuild the app
 */

export function getAudioFileForDevotion(devotionTitle: string): string {
  // Convert title to kebab-case for file name
  const fileName = devotionTitle
    .toLowerCase()
    .replace(/[^a-z0-9\\s-]/g, '') // Remove special characters
    .replace(/\\s+/g, '-') // Replace spaces with hyphens
    .replace(/-+/g, '-') // Replace multiple hyphens with single hyphen
    .trim();
  
  return fileName;
}

/**
 * Dynamically loads audio file for a devotion.
 * Returns null if file doesn't exist or isn't registered.
 * 
 * USAGE:
 * 1. Add your MP3 file to /assets/audio/ with the exact kebab-case name
 * 2. The file will automatically load based on devotion title
 * 3. No manual registration needed!
 */
export function getDynamicAudioSource(devotionTitle: string): any | null {
  const fileName = getAudioFileForDevotion(devotionTitle);
  
  try {
    // Auto-generated mappings for all 365 devotions
    switch (fileName) {
${caseStatements}
      
      default:
        // Audio file not registered - won't show player
        console.log(\`ℹ️  No audio file registered for: \${fileName}.mp3\`);
        return null;
    }
  } catch (error) {
    console.warn(\`⚠️  Could not load audio file: \${fileName}.mp3\`, error);
    return null;
  }
}

/**
 * Get audio source by day of year (1-365)
 */
export function getAudioSourceByDayOfYear(dayOfYear: number): any | null {
  // Import devotionals to get the title for the day
  const { devotionals } = require('@/constants/devotionals');
  const index = (dayOfYear - 1) % 365;
  const devotion = devotionals[index];
  
  if (!devotion) return null;
  
  return getDynamicAudioSource(devotion.title);
}
`;

// Write the generated file
const outputPath = path.join(__dirname, '../utils/audioHelper.ts');
fs.writeFileSync(outputPath, audioHelperContent);

console.log('✅ Generated audioHelper.ts with all 365 audio mappings');
console.log('');
console.log('📋 Next steps:');
console.log('1. Add your MP3 files to /assets/audio/ folder');
console.log('2. Name them using kebab-case (e.g., "finding-peace-in-the-storm.mp3")');
console.log('3. Rebuild your app');
console.log('');
console.log('✨ All audio files are now auto-registered!');

// Also generate a checklist of all required files
const checklistContent = devotionTitles.map((title, index) => {
  const fileName = toKebabCase(title);
  return `Day ${String(index + 1).padStart(3, ' ')}: ${fileName}.mp3`;
}).join('\n');

const checklistPath = path.join(__dirname, '../audio-file-checklist.txt');
fs.writeFileSync(checklistPath, checklistContent);

console.log('📄 Also created audio-file-checklist.txt with all 365 filenames');
