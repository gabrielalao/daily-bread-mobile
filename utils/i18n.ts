const DICTS: Record<SupportedLang, Dict> = { en, fr, da, es, de };

export function t(langRaw: string | undefined, key: string): string {
  const lang = (langRaw as SupportedLang) in DICTS ? (langRaw as SupportedLang) : "en";
  return DICTS[lang][key] ?? en[key] ?? key;
}

export function tParams(langRaw: string | undefined, key: string, params: Record<string, string | number>): string {
  let s = t(langRaw, key);
  for (const [k, v] of Object.entries(params)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
